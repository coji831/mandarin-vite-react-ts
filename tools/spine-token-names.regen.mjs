#!/usr/bin/env node

/**
 * spine-token-names.regen.mjs — regenerate `tools/spine-token-names.json`.
 *
 * The snapshot is the committed, provenance-stamped copy of spine's name list
 * that `scripts/check-spine-parity.mjs` compares the consumer's live token layer
 * against. Regenerating it requires a spine checkout; the GATE does not.
 *
 * Derived here (from spine's emitted CSS, not from a re-reading of tokens.json):
 *   canonical  — every `--<name>` in `packages/tokens/dist/spine.css`, base
 *                `:root` plus the `[data-theme="night-bench"]` overlay (whose
 *                emitted names carry a `--themes-night-bench-` prefix, stripped
 *                here), minus the deprecated aliases. The overlay's value wins
 *                for a name emitted in both blocks: that is the value a
 *                Night Bench consumer is expected to carry.
 *   deprecated — the emitted names preceded by
 *                `/* deprecated: alias of --<canonical> *\/`.
 *
 * Hand-maintained (preserved on regeneration, from the name-mapping table):
 *   domain, retired, themeDelta.
 *
 * Usage: node tools/spine-token-names.regen.mjs --spine <path-to-spine>
 */

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SNAPSHOT = path.join(ROOT, "tools", "spine-token-names.json");

const argSpine = process.argv.indexOf("--spine");
const SPINE = argSpine !== -1 ? process.argv[argSpine + 1] : process.env.SPINE_ROOT;
if (!SPINE) {
  console.error("usage: node tools/spine-token-names.regen.mjs --spine <path-to-spine>");
  process.exit(2);
}

const DIST = path.join(SPINE, "packages", "tokens", "dist", "spine.css");
if (!fs.existsSync(DIST)) {
  console.error(`spine's emitted CSS not found: ${DIST}`);
  process.exit(2);
}

const git = (...args) => execFileSync("git", ["-C", SPINE, ...args], { encoding: "utf8" }).trim();

function block(css, selector) {
  const open = css.indexOf(selector);
  if (open === -1) throw new Error(`spine.css has no \`${selector}\` block`);
  const start = css.indexOf("{", open);
  const end = css.indexOf("}", start);
  return css.slice(start + 1, end);
}

function declarations(text) {
  const out = [];
  const re = /(--[\w-]+)\s*:\s*([^;]+);/g;
  let m;
  while ((m = re.exec(text)) !== null)
    out.push({ name: m[1], value: m[2].replace(/\s+/g, " ").trim() });
  return out;
}

/** Names whose own-line `/* deprecated: alias of --x *\/` comment precedes them. */
function deprecatedFrom(cssLines) {
  const deprecated = {};
  let pending = null;
  for (const line of cssLines) {
    const marker = line.match(/\/\*\s*deprecated:\s*alias of\s+(--[\w-]+)/);
    if (marker) {
      pending = marker[1];
      continue;
    }
    const decl = line.match(/^\s*(--[\w-]+)\s*:/);
    if (decl && pending) {
      // The emitted theme form carries the `--themes-night-bench-` prefix; the
      // deprecated set is the semantic name, so normalise it here.
      const name = decl[1].startsWith("--themes-night-bench-")
        ? `--${decl[1].slice("--themes-night-bench-".length)}`
        : decl[1];
      deprecated[name] = pending;
      pending = null;
    }
  }
  return deprecated;
}

const css = fs.readFileSync(DIST, "utf8");
const cssNoComments = css.replace(/\/\*[\s\S]*?\*\//g, "");

// spine.css is the generic base file; it emits the night-bench overlay's values
// into the same `:root` block under a `--themes-night-bench-<name>` prefix.
const declared = declarations(block(cssNoComments, ":root"));
const THEME_PREFIX = "--themes-night-bench-";
const base = new Map(
  declared.filter((d) => !d.name.startsWith(THEME_PREFIX)).map((d) => [d.name, d.value]),
);
const theme = new Map(
  declared
    .filter((d) => d.name.startsWith(THEME_PREFIX))
    .map((d) => [`--${d.name.slice(THEME_PREFIX.length)}`, d.value]),
);
if (theme.size === 0) {
  console.error(
    "derived 0 night-bench names from spine.css — the emitted theme form changed, re-read the build",
  );
  process.exit(1);
}

const deprecated = deprecatedFrom(css.split("\n"));
if (Object.keys(deprecated).length === 0) {
  console.error(
    "derived 0 deprecated aliases from spine.css — refusing to write a snapshot without them",
  );
  process.exit(1);
}

const canonical = {};
for (const [name, value] of base) canonical[name] = value;
for (const [name, value] of theme) {
  if (deprecated[name]) continue;
  canonical[name] = value;
}
for (const name of Object.keys(deprecated)) delete canonical[name];

const previous = fs.existsSync(SNAPSHOT) ? JSON.parse(fs.readFileSync(SNAPSHOT, "utf8")) : {};

const snapshot = {
  $comment:
    "Committed name list for check:spine-parity. Generated by tools/spine-token-names.regen.mjs; do not hand-edit canonical/deprecated.",
  provenance: {
    source: "spine",
    repository: "C:\\CodeProjects\\Personal\\spine",
    commit: git("rev-parse", "HEAD"),
    commitDate: git("log", "-1", "--format=%cI"),
    stampedAt: new Date().toISOString(),
    derivedFrom:
      "packages/tokens/dist/spine.css (base :root declarations, plus the night-bench values that file emits under a --themes-night-bench- prefix in the same block)",
    aliasesCrossChecked: "registry/renames.md",
    generatedBy: "tools/spine-token-names.regen.mjs",
  },
  derivation: {
    canonical:
      "Every --<name> declared in spine.css, base plus the night-bench overlay (the emitted --themes-night-bench-<name> prefix stripped); the overlay value wins where a name appears in both. Deprecated aliases are excluded — a deprecated name is not a canonical name.",
    deprecated: "Names spine.css marks with a `/* deprecated: alias of --<canonical> */` comment.",
    domain:
      "Hand-maintained: the product-scoped names of the name-mapping table's Domain table, in their post-step-1a spellings (context/topics/spine-mandarin/name-mapping-table.md).",
    retired:
      "Hand-maintained: the names the name-mapping table retires (duplicate-value aliases, dead names, names whose role a canonical name covers). Informational until deleted in step 1b.",
    themeDelta:
      "Hand-maintained: the value-only overrides the Design Lead ruling sanctions — typography families only (ADR-011 consequence 4).",
  },
  canonical,
  deprecated,
  themeDelta: previous.themeDelta ?? [],
  domain: previous.domain ?? [],
  retired: previous.retired ?? [],
};

fs.writeFileSync(SNAPSHOT, await prettier.format(JSON.stringify(snapshot), { parser: "json" }));
console.log(
  `wrote ${path.relative(ROOT, SNAPSHOT)} — ${Object.keys(canonical).length} canonical, ` +
    `${Object.keys(deprecated).length} deprecated, ${snapshot.domain.length} domain, ` +
    `${snapshot.retired.length} retired, ${snapshot.themeDelta.length} theme delta — from spine ${snapshot.provenance.commit}`,
);
