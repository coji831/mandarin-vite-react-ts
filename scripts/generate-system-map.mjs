function collectPages() {
  const inv = readJson(".github/page-inventory.json");
  const pages = Array.isArray(inv?.pages) ? inv.pages : [];
  return pages.map((p) => {
    const hasCode = typeof p.component === "string" && p.component.length > 0;
    const hasStory = typeof p.story === "string" && p.story.length > 0 && exists(p.story);
    const doc = hasStory
      ? p.story
      : typeof p.archetype === "string"
        ? "docs/guides/design/page-archetypes.md"
        : null;
    // Status comes from the machine-checked inventory, not a leaf front-matter.
    let klass;
    if (!hasCode) {
      klass = {
        cat: CAT.DOC_ONLY,
        label: "doc-only",
        flag: "route without page container (redirect/planned)",
      };
    } else if (p.status === "conforms") {
      klass = { cat: CAT.DOCUMENTED, label: CAT.DOCUMENTED };
    } else {
      klass = { cat: CAT.PARTIAL, label: "partial", flag: "page-inventory status diverges" };
    }
    return {
      unit: p.route ?? p.component ?? "<unnamed>",
      code: hasCode,
      docPath: doc,
      docDisplay: doc,
      meta: null,
      klass,
      hasStory,
      gate: "page-inventory",
      area: "A2",
    };
  });
}

function collectShared() {
  const base = "apps/frontend/src/shared";
  return listDirs(path.join(ROOT, base)).map((name) => {
    const doc = `${base}/${name}/README.md`;
    const hasDoc = exists(doc);
    const meta = hasDoc ? readLeafMeta(doc) : null;
    // components/README.md is known-stale: lists 7 of the 32 shared components.
    let countMismatch = false;
    if (name === "components" && hasDoc) {
      const text = fs.readFileSync(path.join(ROOT, doc), "utf-8");
      const listed = countComponentBullets(text, "Available Components") ?? 0;
      const registry = readJson(".github/component-registry.json");
      const sharedCount = Object.entries(registry?.components ?? {}).filter(([, c]) =>
        String(c.importPath ?? "").startsWith("shared/components"),
      ).length;
      countMismatch = listed > 0 && sharedCount > 0 && listed !== sharedCount;
      meta.countListed = listed;
      meta.countShared = sharedCount;
    }
    const klass = classifyUnit({
      codeExists: true,
      docPath: hasDoc ? doc : null,
      meta,
      countMismatch,
    });
    return {
      unit: name,
      code: true,
      docPath: hasDoc ? doc : null,
      docDisplay: hasDoc ? doc : null,
      meta,
      klass,
      countMismatch,
      gate: name === "components" ? "registry-stories + design-audit" : "design-audit",
      area: "A3",
    };
  });
}

