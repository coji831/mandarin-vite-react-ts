// ─── Layer aggregate statuses + router (single-file root) ────────────────────

// Severity ladder for layer aggregate status (worst-of over tracked leaves).
// 0 active · 1 review (attention) · 2 planned (pending/proposed) · 3 missing (broken).
const AGG_SEVERITY = {
  active: 0,
  documented: 0,
  ratified: 0,
  green: 0,
  conforms: 0,
  completed: 0,
  review: 1,
  partial: 1,
  diverges: 1,
  stale: 1,
  undocumented: 1,
  "n/a": 1,
  "doc-only": 1,
  planned: 2,
  deferred: 2,
  proposed: 2,
  "in-progress": 2,
  wip: 2,
  draft: 2,
  missing: 3,
  retired: 3,
  superseded: 3,
  archived: 3,
  deprecated: 3,
};
const AGG_LABEL = ["active", "review", "planned", "missing"];

function aggregateStatusOf(statuses) {
  const sevs = statuses
    .map(
      (s) =>
        AGG_SEVERITY[
          String(s ?? "")
            .trim()
            .toLowerCase()
        ],
    )
    .filter((v) => typeof v === "number");
  if (sevs.length === 0) return "active";
  return AGG_LABEL[Math.max(...sevs)];
}

/** Rewrite a repo-relative path as relative from docs/README.md. */
function relFromRoot(rel) {
  if (!rel || rel === "—") return rel ?? "—";
  if (rel.startsWith("docs/")) return rel.slice("docs/".length);
  return "../" + rel;
}

/** Link a path from docs/README.md, only when it resolves (avoid broken links). */
function linkFromRoot(rel) {
  if (!rel || rel === "—") return rel ?? "—";
  return exists(rel) ? `[${rel}](${relFromRoot(rel)})` : rel;
}

// ─── Tree-map leaf collection + renderer (M0 full tree) ─────────────────────

function hasYamlFrontmatter(rel) {
  const abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) return false;
  return /^---\r?\n/.test(fs.readFileSync(abs, "utf-8").replace(/^\uFEFF/, ""));
}

function prettifyName(s) {
  return String(s).replace(/[-_]/g, " ").trim();
}

function titleize(s) {
  return prettifyName(s).replace(/^\w/, (c) => c.toUpperCase());
}

/** Path-derived display name for a leaf with no front-matter purpose. */
function displayName(rel) {
  const base = path.basename(rel);
  if (/^readme\.md$/i.test(base)) {
    return `${prettifyName(path.basename(path.dirname(rel)))} index`;
  }
  return prettifyName(base.replace(/\.(md|json|html)$/i, ""));
}

/**
 * Normalize a leaf status for the tree: recognized vocab (AGG_SEVERITY) passes
 * through; legacy prose statuses like "RATIFIED — owner-approved …" collapse to
 * their first token ("ratified"). Leading emoji/symbols are stripped first.
 */
function normalizeStatus(raw) {
  if (!raw) return "active";
  const s = String(raw)
    .replace(/^[^\p{L}\p{N}]+/u, "")
    .trim();
  // Placeholder / enumeration statuses (templates: "Draft / Reviewed / Approved",
  // "[Planned/In Progress/Completed]") are NOT a real status — treat as none.
  if (s.includes("/")) return "active";
  const sev = AGG_SEVERITY[s.toLowerCase()];
  if (typeof sev === "number") return s.toLowerCase();
  return s.toLowerCase().split(/[\s—–-]+/)[0] || "active";
}

/** JSON-catalog leaf metadata (status derived from the catalog itself). */
function catalogLeaf(kind) {
  switch (kind) {
    case "decision": {
      const decisions = loadDecisions();
      if (!decisions)
        return {
          purpose: "Machine catalog of ADR/D/OI/BM decisions",
          status: "seeding pending",
        };
      return {
        purpose: "Machine catalog of ADR/D/OI/BM decisions",
        status: aggregateStatusOf(decisions.map((d) => d.status ?? "")),
      };
    }
    case "registry": {
      const reg = readJson(".github/component-registry.json");
      return reg
        ? { purpose: "Shared-component registry — the machine-checked catalog", status: "green" }
        : {
            purpose: "Shared-component registry — the machine-checked catalog",
            status: "seeding pending",
          };
    }
    case "pages": {
      const inv = readJson(".github/page-inventory.json");
      const pages = Array.isArray(inv?.pages) ? inv.pages : [];
      if (pages.length === 0)
        return {
          purpose: "Page route→archetype→story consistency ledger",
          status: "seeding pending",
        };
      return {
        purpose: "Page route→archetype→story consistency ledger",
        status: pages.every((p) => p.status === "conforms") ? "green" : "diverges",
        extra: pageInventoryTldr(pages),
      };
    }
    default:
      return { purpose: "", status: "active" };
  }
}

/** Machine-derived page-inventory TL;DR: "4/16 conform · 12/16 diverges (2 doc-only)". */
function pageInventoryTldr(pages) {
  const active = pages.filter((p) => typeof p.component === "string" && p.component.length > 0);
  const conform = active.filter((p) => p.status === "conforms").length;
  const diverges = active.length - conform;
  const docOnly = pages.length - active.length;
  return `${conform}/${active.length} conform · ${diverges}/${active.length} diverges (${docOnly} doc-only)`;
}

/** Does this root-relative path pass the root's include filter? */
function includedBy(spec, relFromRoot) {
  if (!spec.include) return true;
  return spec.include.test(relFromRoot);
}

function hasExcludedSegment(spec, rel) {
  const segs = rel.split("/");
  return (spec.exclude ?? []).some((x) => segs.includes(x));
}

function makeTreeLeaf(rel, spec, layer, branchOverride) {
  let branch = branchOverride ?? spec.branch ?? "__direct__";
  if (spec.catalog) {
    const c = catalogLeaf(spec.catalog);
    return {
      rel,
      name: displayName(rel),
      layer,
      branch,
      purpose: c.purpose,
      status: c.status,
      extra: c.extra ?? null,
      note: c.status === "seeding pending" ? " ⚠️ catalog missing" : "",
      link: linkFromRoot(rel),
      kind: "catalog",
    };
  }
  if (spec.pointer) {
    return {
      rel,
      name: displayName(rel),
      layer,
      branch,
      purpose: spec.pointer,
      status: "—",
      note: "",
      link: linkFromRoot(rel),
      kind: "pointer",
    };
  }
  // M3: scanned tree leaves read front-matter ONLY — the prose fallback
  // (`**Status:**`/`**Last Updated:**`/`**Purpose:**`) is legacy, kept only for
  // archive/epic/story reads. HTML leaves carry `<!-- last-verified: -->`.
  const meta = readLeafMeta(rel, { prose: false });
  let purpose = meta?.purpose ?? meta?.description ?? null;
  let status = normalizeStatus(meta?.status);
  const date = meta?.["last-verified"] ? parseDate(meta["last-verified"]) : null;
  if (date && daysSince(date) > STALE_DAYS && !RETIREDISH.has(status)) status = "review";
  const isHtml = /\.html$/i.test(rel);
  const fm = isHtml ? false : hasYamlFrontmatter(rel);
  let note = "";
  if (isHtml) {
    // HTML leaf — freshness is the `<!-- last-verified: -->` marker (already
    // parsed into meta["last-verified"]); never a front-matter gap (M3).
    if (!purpose) purpose = displayName(rel);
    if (!meta?.["last-verified"]) note = " ⚠️ no last-verified marker";
  } else if (!fm) {
    note = " ⚠️ no frontmatter";
    if (!purpose) purpose = displayName(rel);
  } else if (!purpose) {
    purpose = displayName(rel);
  }
  // Rare `branch:` override — linkage-noted when used (owner decision 2).
  if (meta?.branch && typeof meta.branch === "string") {
    const ov = String(meta.branch).trim();
    const asLayer = /^[1-7]$/.test(ov) ? +ov : null;
    if (asLayer) {
      layer = asLayer;
      note = `${note ? note + " · " : ""}branch: override → layer ${asLayer}`;
    } else {
      branch = ov;
      note = `${note ? note + " · " : ""}branch: override → ${ov}`;
    }
  }
  return {
    rel,
    name: displayName(rel),
    layer,
    branch,
    purpose,
    status,
    note,
    link: linkFromRoot(rel),
    kind: "doc",
  };
}

/** Is this path an epic/story leaf? Their purpose is carried by the title;
 *  status + last-verified come from the M1 sweep — exempt from the strict
 *  required-fields gate (epic/story/archive leaves are their own class). */
function isEpicStoryLeaf(rel) {
  return /(^|\/)(epic-\d+[^/]*|story-\d+[^/]*)\//.test(rel);
}

/**
 * M3 — hard-flag findings for scanned tree leaves (L1–L5, L7; L6 agentic is
 * special-format and never checked here). Rules:
 *   - .md leaf without a YAML front-matter block → hard flag.
 *   - .md leaf with YAML but missing purpose (∨ description) / status /
 *     last-verified → hard flag.
 *   - HTML leaf without a `<!-- last-verified: YYYY-MM-DD -->` marker → hard
 *     flag (the marker is its freshness marker — never a front-matter gap).
 * DESIGN.md is exempt — its YAML is the machine-consumed design-token schema
 * (name/description/tokens), purpose via `description`, no docs-metadata
 * contract. Catalog + pointer leaves carry no docs front-matter → exempt.
 */
function treeLeafFindings(tree) {
  const findings = [];
  const all = [];
  for (const [layer, branches] of Object.entries(tree)) {
    if (+layer === 6) continue;
    for (const leaves of Object.values(branches)) for (const l of leaves) all.push(l);
  }
  for (const l of all) {
    const rel = l.rel;
    if (l.kind === "catalog" || l.kind === "pointer") continue;
    if (rel === "DESIGN.md" || isEpicStoryLeaf(rel)) continue;
    if (/\.html$/i.test(rel)) {
      const abs = path.join(ROOT, rel);
      const text = fs.existsSync(abs) ? fs.readFileSync(abs, "utf-8") : "";
      if (!/<!--\s*last-verified:\s*\d{4}-\d{2}-\d{2}\s*-->/i.test(text)) {
        findings.push(
          `${rel}: HTML leaf missing \`<!-- last-verified: YYYY-MM-DD -->\` freshness marker`,
        );
      }
      continue;
    }
    if (!hasYamlFrontmatter(rel)) {
      findings.push(
        `${rel}: scanned .md leaf missing YAML front-matter (purpose/status/last-verified required)`,
      );
      continue;
    }
    const meta = readLeafMeta(rel, { prose: false });
    const missing = [];
    if (!meta?.purpose && !meta?.description) missing.push("purpose");
    if (!meta?.status) missing.push("status");
    if (!meta?.["last-verified"]) missing.push("last-verified");
    if (missing.length > 0) {
      findings.push(`${rel}: front-matter missing required field(s): ${missing.join(", ")}`);
    }
  }
  return findings;
}

function collectRootLeaves(spec, layer) {
  const abs = path.join(ROOT, spec.path);
  const leaves = [];
  if (!fs.existsSync(abs)) return leaves;
  if (fs.statSync(abs).isFile()) {
    leaves.push(makeTreeLeaf(spec.path, spec, layer));
    return leaves;
  }
  if (spec.single) {
    // Every recursive file collapses into ONE small branch.
    for (const f of walkFiles(abs)) {
      const rel = path.relative(ROOT, f).replace(/\\/g, "/");
      if (hasExcludedSegment(spec, rel)) continue;
      if (!includedBy(spec, path.relative(spec.path, rel).replace(/\\/g, "/"))) continue;
      leaves.push(makeTreeLeaf(rel, spec, layer));
    }
    return leaves;
  }
  // Group by immediate subdirectory; root-level files → spec.branch.
  for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
    const full = path.join(abs, entry.name);
    const rel = path.join(spec.path, entry.name).replace(/\\/g, "/");
    if (entry.isFile()) {
      if (!includedBy(spec, entry.name)) continue;
      leaves.push(makeTreeLeaf(rel, spec, layer));
    } else if (entry.isDirectory()) {
      const branch = spec.subdirs?.[entry.name] ?? prettifyName(entry.name);
      for (const f of walkFiles(full)) {
        const r = path.relative(ROOT, f).replace(/\\/g, "/");
        if (hasExcludedSegment(spec, r)) continue;
        if (!includedBy(spec, path.relative(spec.path, r).replace(/\\/g, "/"))) continue;
        leaves.push(makeTreeLeaf(r, spec, layer, branch));
      }
    }
  }
  return leaves;
}

function compareLeaves(a, b) {
  const aIdx = /readme\.md$/i.test(a.rel) ? 0 : 1;
  const bIdx = /readme\.md$/i.test(b.rel) ? 0 : 1;
  if (aIdx !== bIdx) return aIdx - bIdx;
  return a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0;
}

/** L6 agentic branch — AGENTS.md special format, leaves with purposes. */
function collectAgenticTree() {
  const { units } = collectAgentic();
  const agentsMeta = readAgentsFrontMatter();
  const marker = agentsMeta?.["last-verified"];
  const d = marker ? parseDate(marker) : null;
  const layerStale = !!d && daysSince(d) > STALE_DAYS;
  // Tree L6 = instructions · agents · skills · control-plane. Conventions live
  // in L5 (tree) / A10 (coverage) — never duplicated here.
  const groups = ["instructions", "agents", "skills", "control-plane"];
  const branches = {};
  for (const u of units) {
    const g = u.group ?? "other";
    if (!groups.includes(g)) continue;
    if (!branches[g]) branches[g] = [];
    branches[g].push({
      rel: u.docPath,
      name: u.unit,
      layer: 6,
      branch: g,
      purpose: u.purpose ?? `${u.unit} (no description)`,
      status: layerStale ? "review" : "active",
      note: u.purpose ? "" : " ⚠️ no description",
      link: linkFromRoot(u.docPath),
    });
  }
  return branches;
}

/** Collect the full tree: { layer → { smallBranch → [leaves] } }. */
function collectTreeLeaves() {
  const tree = {};
  for (const layer of LAYER_ORDER) tree[layer] = {};
  for (const [layer, cfg] of Object.entries(LAYER_ROOTS)) {
    const n = +layer;
    for (const spec of cfg.roots) {
      for (const leaf of collectRootLeaves(spec, n)) {
        if (!tree[leaf.layer][leaf.branch]) tree[leaf.layer][leaf.branch] = [];
        tree[leaf.layer][leaf.branch].push(leaf);
      }
    }
  }
  for (const layer of LAYER_ORDER) {
    for (const branch of Object.keys(tree[layer])) {
      tree[layer][branch].sort(compareLeaves);
    }
  }
  tree[6] = collectAgenticTree();
  return tree;
}

function layerName(layer) {
  return (
    LAYER_ROOTS[layer]?.name ??
    {
      1: "Product / Business",
      2: "Planning",
      3: "Architecture / Decisions",
      4: "Design System",
      5: "Docs / Guides",
      6: "Agentic System",
      7: "Working / Evidence",
    }[layer] ??
    `Layer ${layer}`
  );
}

function layerTreeSummary(branches) {
  const leaves = Object.values(branches ?? {}).flat();
  // An existing-but-retired/superseded leaf is documented, not `missing` — map
  // it to `review` (attention) so `missing` stays reserved for zero leaves.
  const statuses = leaves
    .map((l) => l.status)
    .filter((s) => s && s !== "—")
    .map((s) => (RETIREDISH.has(s) ? "review" : s));
  const agg = leaves.length === 0 ? "missing" : aggregateStatusOf(statuses);
  return { agg, count: leaves.length };
}

function treeStatusCell(status) {
  const s = status ?? "—";
  return s === "review" || s === "missing" ? `**${s}**` : s;
}

function renderLeafTable(leaves) {
  return renderTable(
    ["Purpose", "Status", "Link"],
    leaves.map((l) => [
      l.purpose + (l.note ?? "") + (l.extra ? ` — ${l.extra}` : ""),
      treeStatusCell(l.status),
      l.link ?? "—",
    ]),
  );
}

/**
 * Emit the full generated tree: TOC (one line per layer) → 7 `<details>` big
 * branches → small branches as `####` headings, one table each (flat layers
 * render their leaves directly). Aggregate status = worst-of over existing
 * leaves; a layer with zero leaves = `missing`. Accepts a pre-built tree (M3 —
 * runCheck builds once and reuses it for the invariant).
 */
function renderTree(treeArg) {
  const tree = treeArg ?? collectTreeLeaves();
  const lines = [];
  lines.push("## The tree");
  lines.push("");
  lines.push(
    "Generated full tree — every tracked leaf (purpose · status · link), nested layer → small branch. `review` = stale > 6 weeks (machine override); scanned .md leaves must carry YAML front-matter (purpose/status/last-verified) — absence is a hard `check:system-map` failure; HTML leaves use a `<!-- last-verified: -->` marker.",
  );
  lines.push("");
  // Generated TOC — one line per layer (anchors stay #layer-N; the curated
  // tables that currently duplicate the ids are deleted at M1.5).
  for (const layer of LAYER_ORDER) {
    const { agg, count } = layerTreeSummary(tree[layer]);
    lines.push(
      `- [Layer ${layer} · ${layerName(layer)} — ${agg} · ${count} leaves](#layer-${layer})`,
    );
  }
  lines.push("");
  for (const layer of LAYER_ORDER) {
    const { agg, count } = layerTreeSummary(tree[layer]);
    lines.push(
      `<details id="layer-${layer}"><summary>Layer ${layer} · ${layerName(layer)} — ${agg} · ${count} leaves</summary>`,
    );
    lines.push("");
    const branches = tree[layer];
    if (Object.keys(branches).length === 0) {
      lines.push("_No leaves — layer missing._");
    } else {
      for (const [branch, leaves] of Object.entries(branches)) {
        if (branch !== "__direct__") {
          lines.push(`#### ${titleize(branch)}`);
          lines.push("");
        }
        lines.push(renderLeafTable(leaves));
        lines.push("");
        if (layer === 6 && branch === "instructions") {
          // 18/17 instruction reconcile — machine-emitted from on-disk count.
          const onDisk = listFiles(path.join(ROOT, ".github", "instructions"), (f) =>
            f.endsWith(".instructions.md"),
          ).length;
          lines.push(
            `_${leaves.length} instruction leaves · ${onDisk} on disk — project-workflow is the control-plane gate table._`,
          );
          lines.push("");
        }
      }
    }
    lines.push("</details>");
    lines.push("");
  }
  return lines.join("\n");
}

/**
 * Parse `.github/AGENTS.md` front-matter for the agentic-layer enumeration:
 * `instructions:` (list of `file:` paths) · `agents:` (paths) · `skills:`
 * (paths) · `last-verified:` (scalar). Returns null when AGENTS.md or its
 * front-matter is missing; lists default to empty arrays.
 */
function readAgentsFrontMatter() {
  const abs = path.join(ROOT, ".github", "AGENTS.md");
  if (!fs.existsSync(abs)) return null;
  const text = fs.readFileSync(abs, "utf-8");
  const fm = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!fm) return null;
  const meta = { instructions: [], agents: [], skills: [], "last-verified": null };
  const instructionDescs = {};
  let currentKey = null;
  let currentFile = null;
  for (const line of fm[1].split(/\r?\n/)) {
    const kv = line.match(/^([a-zA-Z][a-zA-Z0-9_-]*):\s*(.*)$/);
    if (kv) {
      currentKey = kv[1];
      currentFile = null;
      const val = kv[2].trim();
      if (val) meta[currentKey] = val.replace(/^["']|["']$/g, "");
    } else if (currentKey === "instructions") {
      // `- file: "..."` + `description: "..."` pairs — capture the purpose.
      const fileKv = line.match(/^\s*-\s+file:\s*["']?(.+?)["']?\s*$/);
      if (fileKv) {
        currentFile = fileKv[1].trim().replace(/["']$/g, "");
        if (!Array.isArray(meta.instructions)) meta.instructions = [];
        meta.instructions.push(currentFile);
        continue;
      }
      const descKv = line.match(/^\s+description:\s*(.+?)\s*$/);
      if (descKv && currentFile) {
        instructionDescs[currentFile] = descKv[1].trim().replace(/^["']|["']$/g, "");
      }
    } else {
      const item = line.match(/^\s*-\s+(.+)$/);
      if (item && currentKey) {
        const raw = item[1].trim();
        const fileKv2 = raw.match(/^file:\s*["']?(.+?)["']?$/);
        const val = fileKv2 ? fileKv2[1].trim() : raw.replace(/^["']|["']$/g, "").trim();
        if (!Array.isArray(meta[currentKey])) meta[currentKey] = [];
        meta[currentKey].push(val);
      }
    }
  }
  meta.instructionDescs = instructionDescs;
  return meta;
}

// ─── Markdown rendering ──────────────────────────────────────────────────────

function escCell(s) {
  return String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ");
}

function renderTable(headers, rows) {
  const lines = [`| ${headers.join(" | ")} |`, `| ${headers.map(() => "---").join(" | ")} |`];
  for (const row of rows) lines.push(`| ${row.map((c) => escCell(c)).join(" | ")} |`);
  return lines.join("\n");
}

function statusCell(klass) {
  const label = klass.label;
  if (klass.cat === CAT.UNDOCUMENTED || klass.cat === CAT.PARTIAL) {
    return `**${label}**${klass.flag ? ` ⚠️ ${klass.flag}` : ""}`;
  }
  return label + (klass.flag ? ` (${klass.flag})` : "");
}

function debtCell(unit, area, klass) {
  const meta = unit.meta ?? {};
  if (klass.cat === CAT.UNDOCUMENTED) {
    const target = meta.target || defaultTarget(area, unit.unit);
    return `**write ${target}**`;
  }
  if (klass.cat === CAT.PARTIAL) {
    const target = meta.target;
    return target ? `close gap: ${target}` : "—";
  }
  return "—";
}

function defaultTarget(area, unitName) {
  switch (area) {
    case "A1":
      return `features/${unitName}/docs/design.md`;
    case "A4":
      return `design.md row + api spec for ${unitName}`;
    case "A6":
      return `packages/${unitName}/README.md`;
    case "A8":
      return unitName === "terraform/" ? "terraform/README.md" : `README for ${unitName}`;
    default:
      return `doc for ${unitName}`;
  }
}

function ownerCell(unit) {
  const meta = unit.meta ?? {};
  return meta["debt-owner"] ? meta["debt-owner"] : "—";
}

