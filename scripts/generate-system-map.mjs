#!/usr/bin/env node

/**
 * generate-system-map.mjs
 *
 * The single docs entrypoint for the two-layer "Map-and-Leaves" system and the
 * full-system coverage + freshness model.
 *
 * The map (`docs/README.md`) and the coverage ledger (`docs/coverage.md`) are
 * GENERATED artifacts. Humans author leaf content + front-matter; this script
 * emits every statused row from those sources of truth. Humans never hand-sync
 * the map or the ledger (R4/R7 — see the two-layer design).
 *
 * Single-file root: `docs/README.md` IS the tree — curated layer tables live in
 * the authored zone (as `<details>` sections), and ONE generated block
 * (`<!-- system-map:generated -->`) holds the "Layers at a glance" router
 * (in-file `#layer-N` anchors), the coverage scoreboard, the machine-derived
 * "Layer detail" lists (Epics · Decisions · area-indexes · A10 micro-readout)
 * and the flags strip. `docs/branches/` was deleted — a stale `docs/branches/`
 * dir is caught by `runCheck` as a linkage note, never a hard fail.
 *
 * Agentic layer (A10): enumerated from `.github/AGENTS.md` front-matter
 * (`instructions:` minus project-workflow · `agents:` · `skills:`), with a
 * directory-scan fallback + linkage note when a list is missing/out of sync.
 * Freshness is layer-level via AGENTS.md `last-verified:`; per-file freshness
 * applies only to conventions (prose `**Last Updated:**`) and control-plane
 * (native markers); `decision-log.json` is exempt.
 *
 * Two modes:
 *   --emit   Reads the sources of truth and writes the generated blocks into
 *            `docs/README.md` and `docs/coverage.md`. Both blocks are delimited
 *            and idempotent: only text strictly between the open/close
 *            delimiters is replaced. If the delimiters do not exist yet, the
 *            block is appended (with a `generated by` header) before the end of
 *            the file. Surrounding hand-authored prose is never touched.
 *   --check  Runs the generation in-memory, diffs the emitted blocks against the
 *            committed files, and exits 1 on any drift. It ALSO runs the
 *            linkage/count-truth checks (declared inventories vs actual; doc-
 *            named paths resolve) and reports their findings. A stale map is a
 *            build failure, never a documentation TODO.
 *
 * Sources of truth (read, never written):
 *   - filesystem scan (code-exists per area)
 *   - leaf front-matter (`purpose/status/last-verified/covers`) with prose
 *     fallbacks (`**Status:**`, `**Last Updated:**`, `**Last Update:**`)
 *   - `.github/page-inventory.json`, `.github/component-registry.json`,
 *     `.github/decision-log.json` (optional — handled gracefully when absent)
 *   - area-index presence (knowledge-base/README.md, getting-started/README.md,
 *     templates/README.md, archive READMEs, …)
 *   - `.github/AGENTS.md` front-matter — the single enumerator for the agentic
 *     layer (instructions 17 · agents 7 · skills 6) + its `last-verified` marker
 *
 * Usage:
 *   node scripts/generate-system-map.mjs --emit
 *   node scripts/generate-system-map.mjs --check
 *
 * Exit codes:
 *   0 = emit wrote the blocks / check PASS (no drift)
 *   1 = source-of-truth missing in a blocking way / check FAIL (drift)
 */

